// Generates cms/content-data.js from content/*.json.
// Cloudflare Pages' Functions bundler (wrangler 3 / esbuild) cannot parse
// `import x from './x.json' with { type: 'json' }`, so the Functions import this
// generated module instead. Run `npm run gen-content` after content/*.json changes;
// tests/content-data.test.mjs fails if it is stale.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const KEYS = ['home', 'services', 'events', 'staff', 'media', 'navigation'];
const root = new URL('../', import.meta.url);

export async function buildContentData() {
    const parts = [];
    for (const key of KEYS) {
        const data = JSON.parse(await readFile(new URL(`content/${key}.json`, root), 'utf8'));
        parts.push(`export const ${key} = ${JSON.stringify(data, null, 2)};\n`);
    }
    return '// GENERATED by scripts/gen-content-data.mjs from content/*.json. Do not edit.\n' + parts.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const out = new URL('cms/content-data.js', root);
    const text = await buildContentData();
    if (process.argv.includes('--check')) {
        const current = await readFile(out, 'utf8').catch(() => '');
        if (current !== text) { console.error('cms/content-data.js is stale: run npm run gen-content'); process.exit(1); }
    } else {
        await writeFile(out, text);
        console.log('Wrote cms/content-data.js');
    }
}
